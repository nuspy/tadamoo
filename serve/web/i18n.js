function T(key, ...args) {
  const s = (STRINGS[LANG] && STRINGS[LANG][key]) ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\d+)\}/g, (_, i) => String(args[+i] ?? ""));
}
// numbers in the page's language
const nfmt = (v, d = 0) => typeof v === "number" && Number.isFinite(v)
  ? v.toLocaleString(LANG === "it" ? "it-IT" : "en-US", { minimumFractionDigits: d, maximumFractionDigits: d }) : "—";
// fill [data-t] elements (text) and [data-t-ph] (placeholder) of a subtree
function applyT(root = document) {
  root.querySelectorAll("[data-t]").forEach(el => { el.textContent = T(el.dataset.t); });
  root.querySelectorAll("[data-t-ph]").forEach(el => { el.setAttribute("placeholder", T(el.dataset.tPh)); });
  root.querySelectorAll("[data-t-aria]").forEach(el => { el.setAttribute("aria-label", T(el.dataset.tAria)); });
  root.querySelectorAll("[data-t-title]").forEach(el => { el.setAttribute("title", T(el.dataset.tTitle)); });
}
